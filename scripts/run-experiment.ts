import { runExperiment } from '../src/prototype/Magnifier/experiment.ts'
import { writeFileSync, mkdirSync } from 'node:fs'

function round6(val: unknown): unknown {
  if (typeof val === 'number') {
    return Math.round(val * 1e6) / 1e6
  }
  if (Array.isArray(val)) {
    return val.map(round6)
  }
  if (val !== null && typeof val === 'object') {
    const out: Record<string, unknown> = {}
    for (const [k, v] of Object.entries(val as Record<string, unknown>)) {
      out[k] = round6(v)
    }
    return out
  }
  return val
}

const result = runExperiment()
const rounded = round6(result)

mkdirSync('data', { recursive: true })
writeFileSync('data/experiment.json', JSON.stringify(rounded, null, 2) + '\n')

mkdirSync('src/case-study/data', { recursive: true })
const header =
  '// GENERATED by `npm run experiment`. Do not edit by hand.\n' +
  '// Source of truth: src/prototype/Magnifier/experiment.ts\n'
const importLine =
  "import type { ExperimentResults } from '../../prototype/Magnifier/experiment'\n\n"
const exportLine =
  'export const EXPERIMENT_RESULTS: ExperimentResults = ' +
  JSON.stringify(rounded, null, 2) +
  ' as const satisfies ExperimentResults\n'

writeFileSync('src/case-study/data/experimentResults.ts', header + importLine + exportLine)

console.log(
  'wrote data/experiment.json and src/case-study/data/experimentResults.ts;',
  result.cells.length,
  'cells',
)
